  await panel.getByLabel('Tags, separated by commas',{exact:true}).fill('first-article')
  await panel.getByLabel('Article URL',{exact:true}).fill('https://example.org/second')
  await panel.getByRole('button',{name:'Extract preview',exact:true}).click()
  await expect(panel.getByLabel('Author',{exact:true})).toHaveValue('')
  await expect(panel.getByLabel('Tags, separated by commas',{exact:true})).toHaveValue('')
