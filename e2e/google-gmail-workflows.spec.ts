test('Gmail reconnects, disconnects and rejects late reads after external disconnect', async ({ page }, testInfo) => {
  const panel = await openGmail(page, false)
  await expect(panel).toContainText('Gmail is not connected')
  await panel.getByRole('tab', { name: 'Account', exact: true }).click()
  await panel.getByLabel('Google OAuth client ID').fill('desktop.apps.googleusercontent.com')
  await page.evaluate(() => sessionStorage.setItem('e2e:gmail-auth-cancel', '1'))
  await panel.getByRole('button', { name: 'Connect with Google' }).click()
  await expect(panel.getByRole('alert')).toContainText('cancelled')
  await expect(panel).toContainText('Not connected to Gmail')
  await attachVisualState(page, testInfo, 'gmail-account-auth-cancelled', panel, panel.getByRole('alert'))
  await page.evaluate(() => sessionStorage.removeItem('e2e:gmail-auth-cancel'))
  await panel.getByRole('button', { name: 'Connect with Google' }).click()
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(2)
  await page.evaluate(() => sessionStorage.setItem('e2e:gmail-delay-detail', '1'))
  await panel.locator('.gmail-manager-message-row').first().click()
  await expect(panel.getByText('Loading message…', { exact: true })).toBeVisible()
  await page.evaluate(() => {
    sessionStorage.setItem('e2e:gmail-connected', '0')
    window.dispatchEvent(new CustomEvent('scriptor:google-account-changed', { detail: { service: 'gmail' } }))
  })
  await expect(panel).toContainText('Gmail is not connected')
  await expect.poll(() => page.evaluate(() => sessionStorage.getItem('e2e:gmail-late-detail-completed'))).toBe('1')
  await expect(panel.locator('.gmail-manager-message-detail')).toHaveCount(0)
  await panel.getByRole('tab', { name: 'Account', exact: true }).click()
  await panel.getByRole('button', { name: 'Connect with Google' }).click()
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(2)
  await panel.getByRole('tab', { name: 'Account', exact: true }).click()
  await panel.getByRole('button', { name: 'Disconnect account' }).click()
  await expect(panel).toContainText('Disconnected from Gmail')
  await attachVisualState(page, testInfo, 'gmail-account-disconnected', panel, panel.getByRole('status').filter({ hasText: 'Disconnected from Gmail' }))
  const history = await calls(page)
  expect(history.some(call => call.cmd === 'google_gmail_disconnect')).toBe(true)
  expect(history.filter(call => /google_calendar_disconnect|collaboration_disconnect/.test(call.cmd))).toHaveLength(0)
})

