import { attachVisualState } from './visual-state-evidence'

async function openGmail(page: Page, connected = true, theme: 'light' | 'dark' = 'light') {
  await page.addInitScript(({ connected }) => {
    sessionStorage.setItem('e2e:google-gmail', '1')
    sessionStorage.setItem('e2e:enable-gmail-plugin', '1')
    if (sessionStorage.getItem('e2e:gmail-connected') === null) sessionStorage.setItem('e2e:gmail-connected', connected ? '1' : '0')
    localStorage.setItem('scriptor:plugins:consent', JSON.stringify({ schemaVersion: 1, savedAt: '2026-10-08T00:00:00Z', data: {
      'scriptor.gmail-manager': { grantedPermissions: ['read', 'write-approved'], allowedVaultIds: ['screenshot-vault'], networkAccess: 'blocked', allowlistedHosts: [], reviewedAt: '2026-10-08T00:00:00Z' },
    } }))
  }, { connected })
  await launchApp(page, { theme })
  await waitForWorkspace(page, { allowHiddenVaultList: true })
  await openCommandPalette(page)
  await runCommand(page, 'Open Gmail Manager')
  const panel = page.locator('.gmail-manager-panel')
  await expect(panel).toBeVisible()
  return panel
}

async function calls(page: Page) {
  return page.evaluate(() => JSON.parse(sessionStorage.getItem('e2e:gmail-calls') ?? '[]') as { cmd: string; payload: Record<string, unknown> }[])
}

