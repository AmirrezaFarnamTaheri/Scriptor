test('Docs discovery stays in the selected folder and a conflicted preview cannot overwrite a stale note', async ({ page }, testInfo) => {
  await page.addInitScript(() => {
    const vaultId = 'screenshot-vault'; const folderId = 'shared-folder'; const path = 'Research Plan.md'
    const raw = JSON.stringify({ schema: 'scriptor.collaboration.mapping.v1', vaultId, folderId, path, peerId: 'legacy-peer', markdown: '---\nstatus: Done\npriority: High\nscore: 12\n---\n\n# Research Plan\n\nResearch [@smith2024].' })
    // Neither an unowned legacy cache nor another account's ancestor can make
    // an overlapping import appear safe to apply without resolving its conflict.
    localStorage.setItem(`scriptor:collaboration:${JSON.stringify([vaultId, folderId, path])}`, raw)
    localStorage.setItem(`scriptor:google-collaboration:v2:${JSON.stringify(['other@example.com', vaultId, folderId, path])}`, raw)
  })
  await launchGoogle(page)
  const panel = await openDrive(page)
  await panel.getByText('Optional Google Docs text translation', { exact: true }).click()
  await panel.getByRole('button', { name: 'Browse documents in this folder', exact: true }).click()
  await panel.getByRole('combobox', { name: 'Choose a Google document', exact: true }).selectOption('shared-doc')
  await panel.getByRole('button', { name: 'Preview translated Google document', exact: true }).click()
  const preview = panel.getByRole('textbox', { name: 'Reviewed translated merge', exact: true })
  await expect(preview).toHaveValue(/Remote translated text/)
  await attachVisualState(page, testInfo, 'docs-translated-preview', panel, preview)
  await panel.getByLabel('I reviewed and accept the text conversion losses for this action').check()
  await expect(panel.getByRole('button', { name: 'Apply reviewed translated merge', exact: true })).toBeDisabled()
  await attachVisualState(page, testInfo, 'docs-overlapping-merge-blocked', panel, preview)
  await preview.fill('# Reviewed text\n\nLocal and remote edits retained.')
  await page.evaluate(() => sessionStorage.setItem('e2e:google-stale-note', '1'))
  await panel.getByRole('button', { name: 'Apply reviewed translated merge', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('content hash mismatch')
  await expect(preview).toHaveValue('# Reviewed text\n\nLocal and remote edits retained.')
  await attachVisualState(page, testInfo, 'docs-stale-content-rejected', panel, panel.getByRole('alert'))
  const history = await calls(page)
  expect(history.filter(call => call.cmd === 'collaboration_write')).toHaveLength(0)
  const importAttempt = history.filter(call => call.cmd === 'vault_save_note').at(-1)!
  expect(importAttempt.payload).toEqual(expect.objectContaining({ expectedVaultId: 'screenshot-vault', path: 'Research Plan.md', dryRun: false }))
  expect(importAttempt.payload.expectedContentHash).toBeTruthy()
  expect(history.filter(call => call.cmd === 'collaboration_read').map(call => call.payload.request)).toEqual(expect.arrayContaining([
    expect.objectContaining({ kind: 'list_docs', folder_id: 'shared-folder' }),
    expect.objectContaining({ kind: 'read_docs', folder_id: 'shared-folder', file_id: 'shared-doc' }),
  ]))
})

