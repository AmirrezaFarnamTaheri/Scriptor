test('Gmail archive, trash and send use distinct reviewed authorization scopes', async ({ page }) => {
  const panel = await openGmail(page)
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(2)
  await panel.locator('.gmail-manager-message-row').first().click()
  await panel.getByRole('button', { name: 'Archive message' }).click()
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(1)
  await panel.locator('.gmail-manager-message-row').first().click()
  await panel.getByRole('button', { name: 'Move to trash' }).click()
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(0)
  await panel.getByRole('tab', { name: 'Compose', exact: true }).click()
  await panel.getByLabel('Recipient (To)').fill('person@example.com')
  await panel.getByLabel('Subject', { exact: true }).fill('Unicode سلام')
  await panel.getByLabel('Message body (plain text)').fill('Plain outgoing text')
  await panel.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Email sent successfully')
  await expect(panel.getByLabel('Message body (plain text)')).toHaveValue('')
  const history = await calls(page)
  const approvals = history.filter(call => call.cmd === 'authorize_sensitive_operation').map(call => call.payload)
  expect(approvals).toEqual(expect.arrayContaining([
    expect.objectContaining({ operation: 'google_gmail_write', scope: 'a1' }),
    expect.objectContaining({ operation: 'google_gmail_write', scope: 'a2' }),
    expect.objectContaining({ operation: 'google_gmail_send', scope: 'gmail-send' }),
  ]))
  const sent = history.find(call => call.cmd === 'google_gmail_send_message')
  expect(sent?.payload.authorizationToken).toBe('e2e-authorization-token')
  expect(Buffer.from(String(sent?.payload.rawMessage), 'base64url').toString('utf8')).toContain('=?UTF-8?B?')
  expect(history.filter(call => /google_calendar_(start_auth|disconnect|create|update|delete)|google_task_(create|update|delete)|collaboration_(start_auth|disconnect|write)/.test(call.cmd))).toHaveLength(0)
})

