test('bibliography file review preserves existing files and literature notes retain citation metadata',async({page})=>{
  await openResearch(page,'Browse bibliography')
  const panel=page.getByRole('dialog',{name:'Bibliography',exact:true})
  await panel.getByLabel('Import a .bib file',{exact:true}).setInputFiles({name:'local.bib',mimeType:'text/plain',buffer:Buffer.from('@article{local2026, title={Local paper}}')})
  await expect(panel.getByRole('region',{name:'Review bibliography file'})).toContainText('Local paper')
  expect(await calls(page,'vault_save_asset')).toHaveLength(0)
  await panel.getByRole('button',{name:'Save reviewed bibliography',exact:true}).click()
  await expect(panel.getByRole('region',{name:'Review bibliography file'})).toHaveCount(0)
  await panel.getByLabel('Import a .bib file',{exact:true}).setInputFiles({name:'new.bib',mimeType:'text/plain',buffer:Buffer.from('@article{different, title={Do not overwrite}}')})
  await panel.getByRole('button',{name:'Save reviewed bibliography',exact:true}).click()
  await expect(panel.getByRole('alert')).toContainText('Destination already exists')
  await panel.getByRole('button',{name:'Cancel file import',exact:true}).click()
  await panel.getByRole('button',{name:'Create literature note',exact:true}).click()
  await expect(panel.getByRole('status')).toContainText('Created a literature note')
  const saved=(await calls(page,'vault_save_note')).find(row=>String(row.payload.path).includes('Literature'))
  expect(saved?.payload.expectedContentHash).toBe('<missing>');expect(saved?.payload.expectedVaultId).toBe('screenshot-vault')
  expect(saved?.payload.markdown).toContain('[@smith2024]');expect(saved?.payload.markdown).toContain('Methods for careful research.')
})

