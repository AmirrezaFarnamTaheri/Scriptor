test('Closing Gmail prevents a pending old query from replacing the reopened inbox', async ({ page }) => {
  const panel = await openGmail(page)
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(2)
  await page.evaluate(() => sessionStorage.setItem('e2e:gmail-delay-list', '1'))
  await panel.getByRole('searchbox').fill('from:new@example.com')
  await panel.getByRole('searchbox').press('Enter')
  await expect(panel.locator('.gmail-manager-message-list')).toHaveAttribute('aria-busy', 'true')
  await closeWorkspacePanel(page, panel)
  await page.evaluate(() => sessionStorage.removeItem('e2e:gmail-delay-list'))
  await openCommandPalette(page)
  await runCommand(page, 'Open Gmail Manager')
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(2)
  await expect.poll(() => page.evaluate(() => sessionStorage.getItem('e2e:gmail-late-list-completed'))).toBe('1')
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(2)
  await expect(panel.locator('.gmail-manager-message-list')).not.toContainText('New search result')
})

test('Gmail controls remain usable with keyboard, RTL and 200 percent app zoom', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 768, height: 960 })
  await page.addInitScript(() => localStorage.setItem('scriptor:ui-zoom', '2'))
  const panel = await openGmail(page)
  await expect(panel.locator('.gmail-manager-message-row')).toHaveCount(2)
  await expect.poll(() => page.evaluate(() => Number(document.body.style.zoom))).toBe(2)
  await page.locator('html').evaluate(element => { element.dir = 'rtl' })
  await panel.getByRole('searchbox').focus()
  await page.keyboard.press('Tab')
  await expect(panel.getByRole('button', { name: 'Search or refresh messages' })).toBeFocused()
  await panel.locator('.gmail-manager-message-row').first().click()
  await expect(panel.locator('.gmail-manager-message-body')).toContainText('Plain message text')
  const metrics = await panel.evaluate(element => {
    const box = element.getBoundingClientRect()
    return { left: box.left, right: box.right, overflow: element.scrollWidth - element.clientWidth }
  })
  expect(metrics.left).toBeGreaterThanOrEqual(0)
  expect(metrics.right).toBeLessThanOrEqual(769)
  expect(metrics.overflow).toBeLessThanOrEqual(1)
  const importButton = panel.getByRole('button', { name: 'Import', exact: true })
  await importButton.scrollIntoViewIfNeeded()
  await expect(importButton).toBeInViewport({ ratio: 1 })
  await settleLayout(page)
  await attachVisualState(page, testInfo, 'gmail-narrow-rtl-zoom-detail', panel, importButton)
  await panel.getByRole('tab', { name: 'Compose', exact: true }).click()
  await panel.getByLabel('Recipient (To)').fill('person@example.com')
  await panel.getByLabel('Subject', { exact: true }).fill('Zoom draft')
  await panel.getByLabel('Message body (plain text)').fill('Usable compose body')
  const sendButton = panel.getByRole('button', { name: 'Send message', exact: true })
  await sendButton.scrollIntoViewIfNeeded()
  await expect(sendButton).toBeInViewport({ ratio: 1 })
  await expect(sendButton).toBeEnabled()
  await attachVisualState(page, testInfo, 'gmail-narrow-rtl-zoom-compose', panel, sendButton)
})
