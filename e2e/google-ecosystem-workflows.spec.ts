import { expect, test, type Page } from '@playwright/test'
import { launchApp, openCommandPalette, runCommand, settleLayout, waitForWorkspace } from './helpers'
import { attachVisualState } from './visual-state-evidence'

type Call = { cmd: string; payload: Record<string, unknown> }
async function calls(page: Page) {
  return page.evaluate(() => JSON.parse(sessionStorage.getItem('e2e:google-ecosystem-calls') ?? '[]') as Call[])
}
async function launchGoogle(page: Page, researchFixture = true) {
  await page.addInitScript(research => {
    sessionStorage.setItem('e2e:google-ecosystem', '1')
    sessionStorage.setItem('e2e:research', research ? '1' : '0')
  }, researchFixture)
  await launchApp(page)
  await waitForWorkspace(page, { allowHiddenVaultList: true })
}
async function openDrive(page: Page) {
  await openCommandPalette(page)
  await runCommand(page, 'Drive collaboration')
  const panel = page.getByRole('region', { name: 'Drive collaboration', exact: true })
  await expect(panel).toBeVisible()
  await expect(panel.getByLabel('Shared folder ID', { exact: true })).toHaveValue('shared-folder')
  return panel
}
async function openGoogleSettings(page: Page) {
  await page.locator('header.topbar').getByRole('button', { name: 'Settings', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Settings' })
  await settings.getByRole('tab', { name: 'Integrations', exact: true }).click()
  return { settings, google: settings.locator('.google-integration-settings') }
}

